const {createServer} = require('./server');
test('HTTP contract, CORS, validation and safe origin injection',async () => {
  const server = createServer({base:'https://example.org',probe:{status:()=>({code:'AUTH_REQUIRED',streamReady:false})}});
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const base = 'http://127.0.0.1:'+server.address().port;
  try {
    const health = await fetch(base+'/health');
    assert.equal(health.headers.get('access-control-allow-origin'),'*');
    const healthData=await health.json();assert.equal(healthData.version,'0.10.1');assert.equal(healthData.apiVersion,1);
    assert.equal(health.headers.get('cache-control'),'no-store');
    const status=await (await fetch(base+'/api/rezka/status')).json();
    assert.equal(status.rezka.code,'AUTH_REQUIRED');
    assert.equal(status.rezka.streamReady,false);
    assert.equal((await fetch(base+'/api/search')).status,410);
    assert.equal((await fetch(base+'/api/rezka/search?q='+encodeURIComponent('Апокалипсис'))).status,503);
    const demo = await (await fetch(base+'/api/demo')).json();
    assert.match(demo.items[0].versions[0].url,/^https:/);
    const js = await (await fetch(base+'/plugin.js',{headers:{host:'evil.invalid'}})).text();
    assert.ok(js.includes('var API = "https://example.org"'));
    new vm.Script(js);
    assert.equal((await fetch(base+'/health',{method:'OPTIONS'})).status,204);
    assert.equal((await fetch(base+'/no-such-route')).status,404);
    assert.equal((await fetch(base+'/health',{method:'POST'})).status,405);
    assert.equal(await (await fetch(base+'/health',{method:'HEAD'})).text(),'');
  } finally { await new Promise(r=>server.close(r)); }
});
